export function biomeReservations(id) {
  if (id === "water") return spaReservations();
  if (id === "clockwork") return cottonReservations();
  if (id === "summer") return capybaraReservations();
  const fixed =
    id === "moon"
      ? [
          { x: -6, z: -4, w: 1.8, d: 1.8 },
          { x: -2, z: 5, w: 2.5, d: 2.5 },
        ]
      : [];
  if (id === "aquapark")
    fixed.push(
      { x: -3, z: -8, w: 11, d: 10 },
      { x: 8, z: 6, w: 10, d: 8 },
      { x: 9, z: -7, w: 10, d: 9 },
      { x: -10, z: -8, w: 9, d: 8 },
    );
  if (RENEWED_ISLANDS[id]) {
    const upper = RENEWED_ISLANDS[id].upper;
    fixed.push({
      x: upper[0],
      z: upper[1],
      w: upper[2] * 2 + 0.7,
      d: upper[3] * 2 + 0.7,
      rx: upper[2] + 0.12,
      rz: upper[3] + 0.12,
    });
    for (const ride of ISLAND_RIDES.filter((r) => r.biome === id)) {
      const item = byItem(ride.type);
      fixed.push({
        x: ride.x,
        z: ride.z,
        w: item.footprint[0],
        d: item.footprint[1],
      });
    }
  }
  const river = BIOME_STYLES[id]?.river;
  if (river)
    fixed.push({
      x: river[0],
      z: river[1],
      w: river[2] * 2,
      d: river[3] * 2,
      rx: river[2] + 0.12,
      rz: river[3] + 0.12,
    });
  const water = BIOME_STYLES[id]?.water;
  if (water)
    fixed.push({
      x: water[0],
      z: water[1],
      w: water[2] * 2 + 0.4,
      d: water[3] * 2 + 0.4,
      rx: water[2] + 0.12,
      rz: water[3] + 0.12,
    });
  return fixed;
}
